/// `RtlUpcaseUnicodeChar(c)`.
pub(super) fn upcase(c: u16) -> u16 {
    if let Ok(i) = EXCEPTIONS.binary_search_by_key(&c, |&(code, _)| code) {
        return EXCEPTIONS[i].1;
    }
    let Some(ch) = char::from_u32(u32::from(c)) else {
        // A surrogate.
        return c;
    };
    let mut upper = ch.to_uppercase();
    match (upper.next(), upper.next()) {
        (Some(single), None) => u16::try_from(u32::from(single)).unwrap_or(c),
        _ => c,
    }
}

/// Whether two names are equal as the system compares them: code unit by code unit, after
/// [`upcase`].
pub(super) fn equal_ignoring_case(a: &[u16], b: &[u16]) -> bool {
    a.len() == b.len() && a.iter().zip(b).all(|(&x, &y)| upcase(x) == upcase(y))
}
